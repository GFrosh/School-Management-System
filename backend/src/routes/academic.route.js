const { Router } = require('express');
const validate = require('../middlewares/validateSchema');
const asyncHandler = require('../middlewares/asyncHandler');
const requireRoles = require('../middlewares/requireRoles');
const { authenticateToken } = require('../middlewares/authenticateToken');
const s = require('../schemas/academic.schema');
const c = require('../controllers/academic.controller');
const router = Router();
const auth = [authenticateToken];
const staff = [authenticateToken, requireRoles(['admin', 'teacher'])];
const admin = [authenticateToken, requireRoles(['admin'])];

router.get('/teaching-assignments/:assignmentId/roster', ...staff, asyncHandler(c.roster));
router.get('/attendance-registers', ...staff, validate(s.registerQuery), asyncHandler(c.getRegister));
router.put('/attendance-registers', ...staff, validate(s.registerBody), asyncHandler(c.saveRegister));
router.post('/attendance-registers/:id/submit', ...staff, validate(s.idParams), asyncHandler(c.submitRegister));
router.get('/students/:id/attendance', ...auth, validate(s.idParams), validate(s.rangeQuery), asyncHandler(c.studentAttendance));
router.get('/assessments', ...staff, validate(s.assessmentQuery), asyncHandler(c.assessments));
router.post('/assessments', ...admin, validate(s.assessmentBody), asyncHandler(c.createAssessment));
router.get('/assessments/:id/scores', ...staff, validate(s.idParams), asyncHandler(c.scores));
router.put('/assessments/:id/scores', ...staff, validate(s.idParams), validate(s.scoresBody), asyncHandler(c.saveScores));
router.post('/assessments/:id/submit', ...staff, validate(s.idParams), asyncHandler(c.submitAssessment));
router.post('/assessments/:id/approve', ...admin, validate(s.idParams), asyncHandler(c.approveAssessment));
router.post('/assessments/:id/publish', ...admin, validate(s.idParams), asyncHandler(c.publishAssessment));
router.post('/results/:id/corrections', ...staff, validate(s.idParams), validate(s.correctionBody), asyncHandler(c.correction));
router.post('/results/:id/corrections/:correctionId/approve', ...admin, validate(s.correctionParams), asyncHandler(c.approveCorrection));
router.get('/enrolments/:id/report-card', ...auth, validate(s.idParams), validate(s.reportQuery), asyncHandler(c.reportCard));
router.get('/me/results', ...[authenticateToken, requireRoles(['student', 'parent'])], asyncHandler(c.meResults));
module.exports = router;
